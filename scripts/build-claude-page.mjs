// Builds the COI Hero Claude page into one HTML file inside the skill folder,
// then zips the skill so it can be uploaded to Claude.
//
//   npm run build:claude
//
// Output: claude/coi-hero/coi-hero.html, claude/coi-hero-skill.zip, and the
// same page as a standalone website for GitHub Pages in docs/index.html.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const skillDir = path.join(root, "claude", "coi-hero");
const pageOut = path.join(skillDir, "coi-hero.html");
const zipOut = path.join(root, "claude", "coi-hero-skill.zip");

const result = await build({
  entryPoints: [path.join(root, "src/claude-page/main.ts")],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  write: false,
  alias: { "@": path.join(root, "src") },
  legalComments: "none",
  logLevel: "warning",
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");

const template = fs.readFileSync(path.join(root, "src/claude-page/template.html"), "utf8");
const page = template.replace("<!-- APP_SCRIPT -->", () => `<script>${js}</script>`);
fs.mkdirSync(skillDir, { recursive: true });
fs.writeFileSync(pageOut, page);

/* GitHub Pages serves the file as-is, so give it the document shell that
   Claude adds when it publishes the page. */
const docsDir = path.join(root, "docs");
const site = [
  "<!doctype html>",
  '<html lang="en">',
  "<head>",
  '<meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">',
  '<meta name="description" content="COI Hero demo: track certificates of insurance, expirations and compliance gaps in your browser.">',
  "<style>html,body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>",
  "</head>",
  "<body>",
  page,
  "</body>",
  "</html>",
  "",
].join("\n");
fs.writeFileSync(path.join(docsDir, "index.html"), site);
fs.writeFileSync(path.join(docsDir, ".nojekyll"), "");

/* The extraction rules and format, generated from the shared code so the
   skill's chat instructions always match what the page and server expect. */
const shared = await build({
  entryPoints: [path.join(root, "src/lib/extractShared.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
  alias: { "@": path.join(root, "src") },
  logLevel: "warning",
});
const { EXTRACTION_RULES, CERTIFICATE_SCHEMA } = await import(
  "data:text/javascript;base64," + Buffer.from(shared.outputFiles[0].text).toString("base64")
);
fs.writeFileSync(
  path.join(skillDir, "extraction-format.md"),
  [
    "# COI Hero extraction format",
    "",
    "<!-- Generated by scripts/build-claude-page.mjs from src/lib/extractShared.ts. Don't edit by hand. -->",
    "",
    "## Rules",
    "",
    EXTRACTION_RULES,
    "",
    "## Format",
    "",
    "One JSON object matching this JSON schema:",
    "",
    "```json",
    JSON.stringify(CERTIFICATE_SCHEMA, null, 2),
    "```",
    "",
  ].join("\n"),
);

/* A minimal zip writer (stored, no compression) so the build needs no extra tools. */
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf) => {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
function zip(entries) {
  const chunks = [];
  const central = [];
  let offset = 0;
  for (const { name, data } of entries) {
    const nameBuf = Buffer.from(name, "utf8");
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    chunks.push(local, nameBuf, data);
    const cen = Buffer.alloc(46);
    cen.writeUInt32LE(0x02014b50, 0);
    cen.writeUInt16LE(20, 4);
    cen.writeUInt16LE(20, 6);
    cen.writeUInt16LE(0x0800, 8);
    cen.writeUInt32LE(crc, 16);
    cen.writeUInt32LE(data.length, 20);
    cen.writeUInt32LE(data.length, 24);
    cen.writeUInt16LE(nameBuf.length, 28);
    cen.writeUInt32LE(offset, 42);
    central.push(cen, nameBuf);
    offset += 30 + nameBuf.length + data.length;
  }
  const cenBuf = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cenBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...chunks, cenBuf, end]);
}

const entries = fs
  .readdirSync(skillDir)
  .filter((f) => !f.startsWith("."))
  .sort()
  .map((f) => ({ name: `coi-hero/${f}`, data: fs.readFileSync(path.join(skillDir, f)) }));
fs.writeFileSync(zipOut, zip(entries));

const kb = (n) => `${Math.round(n / 1024)} KB`;
console.log(`Page: ${path.relative(root, pageOut)} (${kb(Buffer.byteLength(page))})`);
console.log(`Skill: ${path.relative(root, zipOut)} (${entries.map((e) => e.name).join(", ")})`);
console.log(`Website: docs/index.html (${kb(Buffer.byteLength(site))})`);
